"""What the identity use cases need from the outside world. Infrastructure implements these."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol

import numpy as np

from app.identity.domain.entities import (ContinuousSession, Customer, DeviceKey, EnrolmentSession, StepUpChallenge,
                                          VerificationEvent)


class CustomerRepository(Protocol):
    def get(self, customer_id: str) -> Customer | None: ...
    def add(self, customer: Customer) -> Customer: ...
    def by_external_id(self, external_id: str) -> Customer | None: ...
    def newest_first(self) -> list[Customer]: ...


class EnrolmentRepository(Protocol):
    def get(self, session_id: str) -> EnrolmentSession | None: ...
    def add(self, session: EnrolmentSession) -> EnrolmentSession: ...


class DeviceKeyRepository(Protocol):
    def get(self, key_id: str) -> DeviceKey | None: ...
    def add(self, key: DeviceKey) -> DeviceKey: ...
    def active_for(self, customer_id: str) -> list[DeviceKey]: ...


class ChallengeRepository(Protocol):
    def get(self, challenge_id: str) -> StepUpChallenge | None: ...
    def add(self, challenge: StepUpChallenge) -> StepUpChallenge: ...


class ContinuousSessionRepository(Protocol):
    def get(self, session_id: str) -> ContinuousSession | None: ...
    def add(self, session: ContinuousSession) -> ContinuousSession: ...
    def open_for(self, customer_id: str) -> list[ContinuousSession]: ...


class VerificationEventRepository(Protocol):
    def get(self, event_id: str) -> VerificationEvent | None: ...
    def add(self, event: VerificationEvent) -> VerificationEvent: ...
    def for_customer(self, customer_id: str, limit: int) -> list[VerificationEvent]: ...


class IdentityUnitOfWork(Protocol):
    customers: CustomerRepository
    enrolments: EnrolmentRepository
    device_keys: DeviceKeyRepository
    challenges: ChallengeRepository
    continuous_sessions: ContinuousSessionRepository
    events: VerificationEventRepository
    alerts: Any

    def add(self, entity: Any) -> None: ...
    def delete(self, entity: Any) -> None: ...
    def flush(self) -> None: ...
    def commit(self) -> None: ...


@dataclass
class SpoofResult:
    score: float
    model: str
    signals: dict[str, float]


class SpeakerEmbedder(Protocol):
    name: str
    dim: int

    def embed(self, audio: np.ndarray, sample_rate: int) -> np.ndarray: ...


class AntiSpoofScorer(Protocol):
    name: str

    def score(self, audio: np.ndarray, sample_rate: int) -> SpoofResult: ...


class AudioQualityReport(Protocol):
    ok: bool
    duration_s: float
    issues: list[str]

    def as_dict(self) -> dict: ...


class AudioDecoder(Protocol):
    def decode(self, data: bytes, target_sr: int) -> tuple[np.ndarray, int]: ...
    def assess_quality(self, wav: np.ndarray, sr: int, min_seconds: float, max_seconds: float) -> AudioQualityReport: ...


class IrisEngine(Protocol):
    model_name: str

    def decode_image(self, data: bytes) -> np.ndarray: ...
    def process_frame(self, frame: np.ndarray, *, min_focus: float, min_radius: int,
                      hint: tuple[float, float, float] | None) -> Any: ...
    def liveness(self, frames: list[np.ndarray], found: list[bool]) -> dict: ...
    def pick_templates(self, codes: list) -> tuple[list, float]: ...
    def best_match(self, templates: list, codes: list) -> tuple[float | None, list[float | None]]: ...
    def pack_many(self, codes: list) -> tuple[bytes, bytes]: ...
    def unpack_many(self, bits: bytes, mask: bytes) -> list: ...


class Cipher(Protocol):
    def encrypt_vector(self, vec: np.ndarray) -> bytes: ...
    def decrypt_vector(self, blob: bytes, dim: int) -> np.ndarray: ...
    def encrypt_bytes(self, raw: bytes) -> bytes: ...
    def decrypt_bytes(self, blob: bytes) -> bytes: ...
