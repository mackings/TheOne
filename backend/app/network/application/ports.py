"""What the network use cases need from the outside world: storage, the bank's core system and NIBSS.
Infrastructure implements these; nothing in the application layer knows how."""
from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Protocol

from app.identity.application.ports import CustomerRepository, VerificationEventRepository
from app.network.domain.engine import Config, Edge, Snapshot
from app.network.domain.entities import (Account, AnalystAction, Alert, BankAction, Identifier, ImportJob, Label,
                                         Report, Ring, SafeLimit, StatementEntry, Trace, TrainedModel, Transfer,
                                         TransferDecision, TypologyWeight)

AccountKey = tuple[str, str]


class AccountRepository(Protocol):
    def get(self, account_id: str) -> Account | None: ...
    def add(self, account: Account) -> Account: ...
    def find(self, bank_code: str, account_no: str) -> Account | None: ...
    def by_customer(self, customer_id: str) -> list[Account]: ...
    def with_status(self, statuses: set[str]) -> list[Account]: ...
    def with_synthetic_label(self) -> list[Account]: ...
    def bank_codes_for(self, account_no: str) -> list[str]: ...
    def statement_stubs(self, account_no: str) -> list[Account]: ...
    def count(self) -> int: ...
    def ids_for(self, keys: list[AccountKey]) -> dict[AccountKey, str]: ...
    def insert_many(self, rows: list[dict]) -> None: ...


class IdentifierRepository(Protocol):
    def get(self, identifier_id: str) -> Identifier | None: ...
    def add(self, identifier: Identifier) -> Identifier: ...
    def find(self, kind: str, value_hash: str) -> Identifier | None: ...
    def is_linked(self, account_id: str, identifier_id: str) -> bool: ...
    def link(self, account_id: str, identifier_id: str, first_seen: datetime | None = None) -> None: ...
    def links(self, account_id: str, kind: str) -> list[tuple[str, datetime]]: ...


class TransferRepository(Protocol):
    def add(self, transfer: Transfer) -> Transfer: ...
    def insert_many(self, rows: list[dict]) -> None: ...
    def existing_references(self, references: list[str]) -> set[str]: ...
    def count(self) -> int: ...
    def received_since(self, account_id: str, since: datetime) -> list[tuple[str, int]]: ...
    def sent_between(self, account_id: str, since: datetime, until: datetime) -> list[tuple[datetime, str, int, str]]: ...
    def first_received_since(self, since: datetime) -> dict[str, datetime]: ...


class StatementRepository(Protocol):
    def add(self, entry: StatementEntry) -> StatementEntry: ...
    def exists(self, account_id: str, reference: str) -> bool: ...
    def debits_between(self, account_id: str, since: datetime, until: datetime) -> list[tuple[datetime, int, str]]: ...


class ReportRepository(Protocol):
    def add(self, report: Report) -> Report: ...
    def exists(self, account_id: str, kind: str) -> bool: ...


class RingRepository(Protocol):
    def get(self, ring_id: str) -> Ring | None: ...
    def add(self, ring: Ring) -> Ring: ...
    def active(self) -> list[Ring]: ...
    def max_case_no(self) -> int | None: ...
    def id_for_number(self, number: int) -> str | None: ...


class DecisionRepository(Protocol):
    def get(self, decision_id: str) -> TransferDecision | None: ...
    def add(self, decision: TransferDecision) -> TransferDecision: ...
    def by_reference(self, reference: str) -> TransferDecision | None: ...
    def resolved_by(self, event_id: str, other_than: str) -> TransferDecision | None: ...
    def newest(self, limit: int) -> list[TransferDecision]: ...
    def approved_since(self, account_id: str, since: datetime) -> list[tuple[str, int]]: ...
    def recent_contexts(self, account_id: str, limit: int) -> list[dict | None]: ...
    def stopped_to(self, account_ids: list[str], limit: int) -> list[TransferDecision]: ...
    def count(self) -> int: ...


class ActionRepository(Protocol):
    def add(self, action: AnalystAction) -> AnalystAction: ...
    def for_ring(self, ring_id: str) -> list[AnalystAction]: ...


class SafeLimitRepository(Protocol):
    def get(self, account_id: str) -> SafeLimit | None: ...
    def add(self, limit: SafeLimit) -> SafeLimit: ...


class AlertRepository(Protocol):
    def get(self, alert_id: str) -> Alert | None: ...
    def add(self, alert: Alert) -> Alert: ...
    def newest(self, open_only: bool, limit: int) -> list[Alert]: ...
    def open_count(self) -> int: ...


class LabelRepository(Protocol):
    def get(self, account_id: str) -> Label | None: ...
    def add(self, label: Label) -> Label: ...
    def all(self) -> list[Label]: ...


class BankActionRepository(Protocol):
    def get(self, action_id: str) -> BankAction | None: ...
    def add(self, action: BankAction) -> BankAction: ...
    def newest(self, status: str | None, limit: int) -> list[BankAction]: ...
    def for_account(self, account_id: str, kind: str, statuses: set[str]) -> list[BankAction]: ...


class TypologyWeightRepository(Protocol):
    def all(self) -> list[TypologyWeight]: ...
    def replace_all(self, weights: list[TypologyWeight]) -> None: ...


class ModelRepository(Protocol):
    def get(self, key: str) -> TrainedModel | None: ...
    def add(self, model: TrainedModel) -> TrainedModel: ...


class TraceRepository(Protocol):
    def add(self, trace: Trace) -> Trace: ...
    def for_ring(self, ring_id: str) -> list[Trace]: ...


class ImportJobRepository(Protocol):
    def get(self, job_id: str) -> ImportJob | None: ...
    def add(self, job: ImportJob) -> ImportJob: ...
    def newest(self, limit: int) -> list[ImportJob]: ...


class GraphReader(Protocol):
    """Reads the transfer graph into the in-memory snapshot the detection engine works on."""

    def load_snapshot(self, cfg: Config, at: datetime) -> Snapshot: ...
    def reload_accounts(self, snap: Snapshot, account_ids: set[str], cfg: Config) -> None: ...
    def transfers_by_reference(self, references: list[str]) -> list[Edge]: ...


class NetworkUnitOfWork(Protocol):
    accounts: AccountRepository
    identifiers: IdentifierRepository
    transfers: TransferRepository
    statements: StatementRepository
    reports: ReportRepository
    rings: RingRepository
    decisions: DecisionRepository
    actions: ActionRepository
    safe_limits: SafeLimitRepository
    alerts: AlertRepository
    labels: LabelRepository
    bank_actions: BankActionRepository
    weights: TypologyWeightRepository
    models: ModelRepository
    traces: TraceRepository
    import_jobs: ImportJobRepository
    graph: GraphReader
    customers: CustomerRepository
    events: VerificationEventRepository

    def data_version(self) -> int: ...
    def flush(self) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def close(self) -> None: ...


UnitOfWorkFactory = Callable[[], NetworkUnitOfWork]


@dataclass
class BankResult:
    ok: bool
    body: Any = None
    error: str | None = None
    meta: dict = field(default_factory=dict)


@dataclass
class AccountProfile:
    ok: bool
    error: str | None = None
    opened_at: datetime | None = None
    full_name: str | None = None
    kyc_tier: int | None = None
    status: str | None = None


class BankConnector(Protocol):
    """The bank's core system, shaped on the Open Banking Nigeria API."""

    name: str

    def get_account(self, account_no: str) -> BankResult: ...
    def get_customer_limits(self, account_no: str) -> BankResult: ...
    def get_statement(self, account_no: str, start: datetime, end: datetime) -> BankResult: ...
    def place_hold(self, account_no: str, amount_naira: str, reference: str, reason: str, start: datetime, end: datetime) -> BankResult: ...
    def remove_hold(self, account_no: str, reference: str) -> BankResult: ...
    def block_pnd(self, account_no: str, message: str) -> BankResult: ...
    def account_profile(self, account_no: str) -> AccountProfile: ...
    def daily_limit_kobo(self, account_no: str) -> tuple[bool, int | None]: ...
    def available_balance(self, account_no: str) -> str | None: ...


class NibssError(RuntimeError):
    pass


class MissingColumns(ValueError):
    """A bank file's header does not match the chosen format."""

    def __init__(self, message: str, missing: list[str], found: list[str]):
        super().__init__(message)
        self.missing, self.found = missing, found


class NibssConnector(Protocol):
    """Cross-bank traces and the industry BVN watch-list."""

    name: str

    def trace(self, bank_code: str, account_no: str, received: list[dict]) -> list[dict]: ...
    def watchlisted(self, bvn: str) -> bool: ...
